"""Per-trace and corpus-level generator.

Usage:
    python generate.py --one  <trace_root>\trace_<name>
    python generate.py --all  <trace_root>  --out-mirror  <paper_output_root>

For each trace_* folder this writes a self-contained subfolder:
    <trace>/_paper_report/
        ├── README.md          (index pointing at the other four files)
        ├── flow_report.md     (10-stage key/cipher/loop flow)
        ├── report.md          (per-sample metrics + RC-01..07 checklist)
        ├── unified_report.md  (consolidated view)
        └── sample_view.json   (raw adapter view used by all writers)

If --out-mirror is set, the same _paper_report subfolder is also mirrored to
    <out-mirror>/<trace>/_paper_report/...
so the dataset can be browsed at the mirror location.

It additionally writes a corpus-level aggregate file at:
    <out-mirror>/paper_aggregate.json
    <out-mirror>/paper_aggregate.md
    <out-mirror>/per_sample_index.json

Legacy files (flow_report.md / report.md / unified_report.md / sample_view.json
written at the trace root by older versions of this script) are automatically
moved into _paper_report when they are encountered, so re-running the generator
silently cleans up the previous layout.
"""
from __future__ import annotations

import argparse
import json
# add math for ceil-based p95
import math
import statistics
import sys
import traceback
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from schema import adapt, load_analysis_report  # noqa: E402
from writers import write_flow_report, write_paper_report, write_unified_report  # noqa: E402


def _maybe_load_dll_roles() -> dict | None:
    # Resolve `assets/dll_roles.json` across plausible layouts:
    #   (1) <repo>/assets/            (repo root layout — most common)
    #   (2) onHost/assets/             (bundled onHost layout)
    here = Path(__file__).resolve()
    candidates = [
        here.parent.parent.parent / "assets" / "dll_roles.json",
        here.parent.parent / "assets" / "dll_roles.json",
    ]
    cat = next((p for p in candidates if p.exists()), None)
    if cat is None:
        return None
    try:
        with cat.open("r", encoding="utf-8") as fh:
            data = json.load(fh)
        # Ransack schema: {"_meta": {...}, "roles": {dll_name: role_string}}
        if isinstance(data, dict) and "roles" in data and isinstance(data["roles"], dict):
            return {k: v for k, v in data["roles"].items()
                    if isinstance(v, str) and not k.startswith("_comment")}
        if isinstance(data, dict) and "by_dll" in data:
            return data["by_dll"]
        if isinstance(data, dict):
            return data
    except Exception:
        return None
    return None


REPORT_SUBDIR = "_paper_report"
REPORT_FILES = ("flow_report.md", "report.md", "unified_report.md",
                "sample_view.json", "README.md")


def _build_readme(view: dict) -> str:
    rec = view["recovery"]
    pm = view["paper_metrics"]
    return "\n".join([
        f"# `{view['session_id']}` — paper report index",
        "",
        f"- **family**: `{view['family']}`",
        f"- **execution_quality**: `{view['execution_quality']}`",
        f"- **recovery tier**: `{rec['tier']}` "
        f"({rec['passed_count']}/{rec['total_cases']} RC cases passed)",
        f"- **paper binary flags**: NO_PAYLOAD_RUN=`{rec['tier'] == 'NO_PAYLOAD_RUN'}` · "
        f"VALIDATED=`{rec['validated']}`",
        f"- **primary cipher**: `{view['primary_cipher']}` "
        f"(confidence {view['primary_cipher_confidence']})",
        f"- **per-sample metrics**: Key Detection=`{pm['key_detection']}` · "
        f"File Recoverability=`{pm['file_recoverable']}` · "
        f"Loop-Based Behavior Recovery=`{pm['loop_recovery']}`",
        "",
        "## Files in this folder",
        "",
        "| file | what it contains |",
        "|---|---|",
        "| [flow_report.md](flow_report.md) | 10-stage key/cipher/loop flow "
        "(Stage 1 identity → Stage 10 Mermaid diagram). |",
        "| [report.md](report.md) | Per-sample verdict + RC-01..07 strict-case checklist "
        "+ §10 decryption-tool synthesis evidence (cipher / round count / I/O chunk size). |",
        "| [unified_report.md](unified_report.md) | Consolidated single-page view: identity, recovery verdict, "
        "API trace, file ops, loop categories, top-10 scored loops, references. |",
        "| [sample_view.json](sample_view.json) | Raw flattened view emitted by the adapter — "
        "every value rendered into the three reports lives here. The corpus aggregator (`paper_aggregate.md`) "
        "reads these JSONs across all traces. |",
        "| README.md | this index. |",
        "",
        f"_Generated by `report.generate` on {view['generated_at']}._",
        "",
    ])


def _cleanup_legacy_root_files(trace_root: Path, subdir: Path) -> int:
    """Move any pre-existing report files left at the trace root into the
    new _paper_report subdir, so re-running silently fixes the old layout."""
    moved = 0
    for name in REPORT_FILES:
        legacy = trace_root / name
        if legacy.exists() and legacy.is_file():
            target = subdir / name
            try:
                if target.exists():
                    legacy.unlink()
                else:
                    legacy.replace(target)
                moved += 1
            except Exception:
                continue
    return moved


def process_trace(trace_root: Path, dll_roles: dict | None,
                  mirror_root: Path | None = None) -> dict:
    ar, ar_path, err = load_analysis_report(trace_root)
    result = {
        "trace": trace_root.name,
        "trace_root": str(trace_root),
        "analysis_report_path": str(ar_path) if ar_path else None,
        "status": "ok" if ar else "skipped",
        "reason": err,
    }
    if not ar:
        return result

    try:
        view = adapt(ar, trace_root, dll_roles=dll_roles)
    except Exception as ex:
        result.update(status="error", reason=f"adapt: {ex}",
                      traceback=traceback.format_exc())
        return result

    writes_targets: list[Path] = [trace_root / REPORT_SUBDIR]
    if mirror_root is not None:
        writes_targets.append(mirror_root / trace_root.name / REPORT_SUBDIR)

    for target in writes_targets:
        try:
            target.mkdir(parents=True, exist_ok=True)
            # Pull any legacy files (left by older runs) into the subdir before
            # writing the fresh content.
            _cleanup_legacy_root_files(target.parent, target)
            (target / "flow_report.md").write_text(write_flow_report(view), encoding="utf-8")
            (target / "report.md").write_text(write_paper_report(view), encoding="utf-8")
            (target / "unified_report.md").write_text(write_unified_report(view), encoding="utf-8")
            (target / "sample_view.json").write_text(json.dumps(view, indent=2, ensure_ascii=False),
                                                    encoding="utf-8")
            (target / "README.md").write_text(_build_readme(view), encoding="utf-8")
        except Exception as ex:
            result.update(status="write_error", reason=f"write {target}: {ex}")
            return result

    result.update(
        family=view["family"],
        execution_quality=view["execution_quality"],
        rec_tier=view["recovery"]["tier"],
        rec_validated=view["recovery"]["validated"],
        rec_passed=view["recovery"]["passed_count"],
        passed_case_ids=[c["case_id"] for c in view["recovery"]["passed_cases"]],
        primary_cipher=view["primary_cipher"],
        loops_total=view["totals"]["loops_total"],
        loops_crypto=view["totals"]["loops_crypto"],
        rng_calls=view["totals"]["rng_calls"],
        sym_encrypt_calls=view["totals"]["sym_encrypt_calls"],
        writes=view["totals"]["writes"],
        reads=view["totals"]["reads"],
        deletes=view["totals"]["deletes"],
        moves=view["totals"]["moves"],
        sym_keys_unique=view["totals"]["sym_keys_unique"],
        asym_blobs=view["totals"]["asym_blobs"],
        sink_count=view["totals"]["sink_count"],
        embedded_root_count=view["totals"]["embedded_root_count"],
        hardcoded_key_ratio=view["totals"]["hardcoded_key_ratio"],
        residue_class=view["residue"]["class"],
        residue_matches=view["residue"]["total_matches"],
        key_detection=view["paper_metrics"]["key_detection"],
        file_recoverable=view["paper_metrics"]["file_recoverable"],
        loop_recovery=view["paper_metrics"]["loop_recovery"],
        runtime_sec=view.get("runtime_sec"),
        cross_axis=view["cross_axis"],
        coverage_notes=view.get("coverage_notes") or [],
    )
    return result


def aggregate(results: list[dict], out_dir: Path) -> dict:
    ok = [r for r in results if r.get("status") == "ok"]

    funnel = Counter()
    for r in ok:
        funnel[r["execution_quality"]] += 1
    for r in results:
        if r.get("status") != "ok":
            funnel[f"skipped:{r.get('reason') or 'unknown'}"] += 1

    rc_match = Counter()
    samples_with_any_match = 0
    for r in ok:
        if r["passed_case_ids"]:
            samples_with_any_match += 1
        for cid in r["passed_case_ids"]:
            if cid:
                rc_match[cid] += 1

    loop_axis = {"crypto": 0, "non_crypto": 0}
    families = Counter()
    cipher_dist = Counter()
    tier_dist = Counter()
    for r in ok:
        families[r["family"]] += 1
        cipher_dist[r["primary_cipher"]] += 1
        tier_dist[r["rec_tier"]] += 1
        loop_axis["crypto"] += r["loops_crypto"]
        # Non-crypto hot loops are reported as a single measured bucket. The
        # per-sample feed does not carry a normal-vs-unknown sub-classification,
        # so we do NOT invent one (an earlier version split this 70/30, which
        # was fabricated, not measured).
        loop_axis["non_crypto"] += max(r["loops_total"] - r["loops_crypto"], 0)

    cross_axis_total = Counter()
    for r in ok:
        for k, v in (r.get("cross_axis") or {}).items():
            cross_axis_total[k] += int(v or 0)

    def _stats(vals):
        vals = [v for v in vals if v is not None]
        if not vals:
            return {"n": 0}
        vals_sorted = sorted(vals)
        # nearest-rank p95 (ceil-based, clamped)
        _n = len(vals_sorted)
        _p95_idx = min(_n - 1, max(0, math.ceil(_n * 0.95) - 1))
        return {
            "n": _n,
            "min": vals_sorted[0],
            "median": statistics.median(vals_sorted),
            "p95": vals_sorted[_p95_idx],
            "max": vals_sorted[-1],
            "mean": round(statistics.fmean(vals_sorted), 3),
            "total": sum(vals_sorted),
        }

    perf = {
        "runtime_sec": _stats([r["runtime_sec"] for r in ok if r.get("runtime_sec") is not None]),
        "loops_total": _stats([r["loops_total"] for r in ok]),
        "writes": _stats([r["writes"] for r in ok]),
        "reads": _stats([r["reads"] for r in ok]),
        "rng_calls": _stats([r["rng_calls"] for r in ok]),
        "sym_encrypt_calls": _stats([r["sym_encrypt_calls"] for r in ok]),
        "sym_keys_unique": _stats([r["sym_keys_unique"] for r in ok]),
        "asym_blobs": _stats([r["asym_blobs"] for r in ok]),
        "sink_count": _stats([r["sink_count"] for r in ok]),
    }

    paper_metric_counts = Counter()
    for r in ok:
        for k in ("key_detection", "file_recoverable", "loop_recovery"):
            paper_metric_counts[f"{k}:{r[k]}"] += 1

    summary = {
        "total_candidates": len(results),
        "instrumented_and_analysed": len(ok),
        "funnel": dict(funnel),
        "rc_match_counts": dict(rc_match),
        "rc_no_match_count": len(ok) - samples_with_any_match,
        "tier_distribution": dict(tier_dist),
        "family_distribution_top20": dict(families.most_common(20)),
        "primary_cipher_top20": dict(cipher_dist.most_common(20)),
        "loop_axis_aggregate": loop_axis,
        "cross_axis_aggregate": dict(cross_axis_total),
        "paper_metric_breakdown": dict(paper_metric_counts),
        "performance_stats": perf,
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "paper_aggregate.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    (out_dir / "paper_aggregate.md").write_text(_aggregate_markdown(summary), encoding="utf-8")
    (out_dir / "per_sample_index.json").write_text(
        json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    return summary


def _aggregate_markdown(s: dict) -> str:
    out: list[str] = []
    out += [
        "# Corpus-level Aggregate (paper §IV evidence)",
        "",
        "> Auto-generated from per-sample `sample_view.json` files. "
        "Populates the paper's §IV corpus tables.",
        "",
        "## Corpus selection funnel",
        "",
        "| status / exclusion reason | count |",
        "|---|---:|",
    ]
    funnel = s["funnel"]
    out.append(f"| Instrumented and analysed (analysis_report produced) | {s['instrumented_and_analysed']} |")
    out.append(f"| Total candidates attempted | {s['total_candidates']} |")
    for k in sorted(funnel):
        out.append(f"| `{k}` | {funnel[k]} |")
    out += ["", "## Table V — Per-case decision frequency (RQ2)", "",
            "| ID | technique | matches |", "|---|---|---:|"]
    rc_lookup = {
        "RC-01": "Complete RSA private blob",
        "RC-02": "RSA private blob or consistent prime",
        "RC-03": "Memory-residue prime scan",
        "RC-04": "Limited observed RNG ancestry",
        "RC-05": "Observed RNG-to-keygen path",
        "RC-06": "Decisive cipher artifact",
        "RC-07": "Symmetric session-material candidate",
    }
    for cid in sorted(rc_lookup):
        out.append(f"| {cid} | {rc_lookup[cid]} | {s['rc_match_counts'].get(cid, 0)} |")
    out.append(f"| — | confident no-match (infeasibility) | {s['rc_no_match_count']} |")

    out += ["", "## Loop-axis classification (RQ2)", "",
            "| state | count |", "|---|---:|"]
    la = s["loop_axis_aggregate"]
    total_loops = sum(la.values()) or 1
    for k in ("crypto", "non_crypto"):
        out.append(f"| `{k}.*` | {la[k]} ({la[k] * 100 // total_loops}%) |")
    out.append(f"| total hot loops | {total_loops} |")

    out += ["", "## Cross-axis corroboration aggregate (RQ2)", "",
            "| verdict | count |", "|---|---:|"]
    for k, v in sorted(s["cross_axis_aggregate"].items(), key=lambda x: -x[1]):
        out.append(f"| `{k}` | {v} |")

    out += ["", "## Performance & dataset stats (RQ3)", "",
            "| metric | n | min | median | mean | p95 | max | total |",
            "|---|---:|---:|---:|---:|---:|---:|---:|"]
    for k, st in s["performance_stats"].items():
        if st.get("n", 0) == 0:
            out.append(f"| {k} | 0 | — | — | — | — | — | — |")
            continue
        out.append(
            f"| {k} | {st['n']} | {st['min']} | {st['median']} | {st['mean']} | "
            f"{st['p95']} | {st['max']} | {st['total']} |"
        )

    out += ["", "## Recovery tier distribution", "",
            "| tier | count |", "|---|---:|"]
    for k, v in sorted(s["tier_distribution"].items(), key=lambda x: -x[1]):
        out.append(f"| `{k}` | {v} |")

    out += ["", "## Per-sample metric breakdown", "",
            "| metric:value | count |", "|---|---:|"]
    for k, v in sorted(s["paper_metric_breakdown"].items()):
        out.append(f"| `{k}` | {v} |")

    out += ["", "## Top 20 families in the corpus", "",
            "| family | count |", "|---|---:|"]
    for k, v in s["family_distribution_top20"].items():
        out.append(f"| `{k}` | {v} |")

    out += ["", "## Top 20 primary ciphers identified", "",
            "| cipher | count |", "|---|---:|"]
    for k, v in s["primary_cipher_top20"].items():
        out.append(f"| `{k}` | {v} |")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--one", help="Process a single trace_* directory.")
    g.add_argument("--all", help="Process every trace_* child of this directory.")
    ap.add_argument("--out-mirror", help="Optional directory to mirror outputs into "
                    "(also used for the corpus aggregate file).", default=None)
    ap.add_argument("--limit", type=int, default=0,
                    help="Limit to first N traces (for testing). 0 = unlimited.")
    args = ap.parse_args()

    dll_roles = _maybe_load_dll_roles()
    mirror_root = Path(args.out_mirror) if args.out_mirror else None

    results: list[dict] = []
    if args.one:
        results.append(process_trace(Path(args.one), dll_roles, mirror_root))
    else:
        root = Path(args.all)
        traces = sorted([p for p in root.iterdir() if p.is_dir() and p.name.startswith("trace_")])
        if args.limit:
            traces = traces[: args.limit]
        for i, t in enumerate(traces, 1):
            r = process_trace(t, dll_roles, mirror_root)
            results.append(r)
            if i % 25 == 0 or i == len(traces):
                ok = sum(1 for x in results if x["status"] == "ok")
                print(f"[{i}/{len(traces)}] {t.name} -> {r['status']} ({ok} ok so far)", flush=True)

    if mirror_root:
        aggregate(results, mirror_root)
    else:
        # Even with --one we emit a tiny per-sample summary next to the trace
        pass

    ok = sum(1 for r in results if r["status"] == "ok")
    skipped = sum(1 for r in results if r["status"] != "ok")
    print(f"\nDone. ok={ok} skipped/failed={skipped} total={len(results)}")
    if args.out_mirror:
        print(f"Aggregate written to {Path(args.out_mirror) / 'paper_aggregate.md'}")


if __name__ == "__main__":
    main()
